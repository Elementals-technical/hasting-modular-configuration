#!/usr/bin/env node
// Personal AI-layer tooling for the Hastings repo: backup, collision check and Claude wrapper sync.
// Dependency-free Node ESM; runs from the repository root on macOS, Linux and Windows.
//
//   node ai-env.mjs list
//   node ai-env.mjs snapshot <label>
//   node ai-env.mjs verify [snapshot-id|latest]
//   node ai-env.mjs restore <snapshot-id|latest> [path-prefix ...]
//   node ai-env.mjs collisions [--ref <ref>]... [--all-remotes] [--quiet]
//   node ai-env.mjs sync [--quiet]
//   node ai-env.mjs check-sync
//
// Env: AI_ENV_STORE overrides the backup store (used by test-tooling.mjs).

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const SLUG = "hastings-modular-configuration";
const DEFAULT_REFS = ["origin/phase-2/staging", "origin/phase-2/production"];
// Personal paths; everything here must stay untracked on every ref.
const PERSONAL_FILES = ["AGENTS.local.md", "CLAUDE.local.md", ".claude/settings.local.json"];
const PERSONAL_DIRS = ["docs/ai", ".claude/skills"];
const PERSONAL_SKILL_PREFIX = ".agents/skills/local-";
// Snapshotted in addition to repository files (lives inside .git).
const GIT_EXCLUDE = ".git/info/exclude";
// Sources of Claude wrappers: personal workflows and team skills.
const SKILL_SOURCES = [".agents/skills", "skills"];
const WRAPPER_DIR = ".claude/skills";
const WRAPPER_MARKER = "<!-- generated by ai-env.mjs sync; edit the canonical skill, not this file -->";
const COPIED_KEYS = ["name", "description", "disable-model-invocation", "argument-hint"];

const args = process.argv.slice(2);
const command = args[0];
const quiet = args.includes("--quiet");

function fail(message, code = 1) {
  console.error(`ai-env: ${message}`);
  process.exit(code);
}

function git(gitArgs, opts = {}) {
  return execFileSync("git", gitArgs, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 << 20, ...opts });
}

function repoRoot() {
  try {
    return git(["rev-parse", "--show-toplevel"]).trim();
  } catch {
    return fail("not inside a git repository");
  }
}

function storeDir() {
  if (process.env.AI_ENV_STORE) return process.env.AI_ENV_STORE;
  if (process.platform === "win32" && process.env.LOCALAPPDATA) return path.join(process.env.LOCALAPPDATA, "ai-env", SLUG);
  return path.join(os.homedir(), ".local", "share", "ai-env", SLUG);
}

const toPosix = (p) => p.split(path.sep).join("/");
const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

function walk(root, rel) {
  const abs = path.join(root, rel);
  if (!fs.existsSync(abs)) return [];
  const stat = fs.statSync(abs);
  if (stat.isFile()) return [toPosix(rel)];
  const out = [];
  for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
    if (entry.name === ".DS_Store") continue;
    out.push(...walk(root, path.join(rel, entry.name)));
  }
  return out;
}

function personalSkillDirs(root) {
  const base = path.join(root, ".agents", "skills");
  if (!fs.existsSync(base)) return [];
  return fs
    .readdirSync(base, { withFileTypes: true })
    .filter((d) => d.isDirectory() && d.name.startsWith("local-"))
    .map((d) => `.agents/skills/${d.name}`);
}

// Files that belong to the personal layer (generated wrappers excluded: sync recreates them).
function personalFiles(root, { includeGitExclude = true } = {}) {
  const files = [];
  for (const f of PERSONAL_FILES) files.push(...walk(root, f));
  for (const d of personalSkillDirs(root)) files.push(...walk(root, d));
  files.push(...walk(root, "docs/ai"));
  if (includeGitExclude && fs.existsSync(path.join(root, GIT_EXCLUDE))) files.push(GIT_EXCLUDE);
  return [...new Set(files)].sort();
}

function isPersonalPath(p) {
  return (
    PERSONAL_FILES.includes(p) ||
    PERSONAL_DIRS.some((d) => p === d || p.startsWith(`${d}/`)) ||
    p.startsWith(PERSONAL_SKILL_PREFIX)
  );
}

// ---------- snapshot / verify / restore / list ----------

function snapshotsDir(store) {
  return path.join(store, "snapshots");
}

function resolveSnapshot(store, id) {
  const dir = snapshotsDir(store);
  let target = id;
  if (!id || id === "latest") {
    const latest = path.join(store, "LATEST");
    if (!fs.existsSync(latest)) fail("no snapshots yet; run: node ai-env.mjs snapshot <label>");
    target = fs.readFileSync(latest, "utf8").trim();
  }
  const file = path.join(dir, `${target}.json`);
  if (!fs.existsSync(file)) fail(`snapshot not found: ${target}`);
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function cmdSnapshot(root) {
  const label = (args[1] || "").replace(/[^A-Za-z0-9._-]/g, "-");
  if (!label || label.startsWith("--")) fail("usage: snapshot <label>");
  const store = storeDir();
  fs.mkdirSync(path.join(store, "objects"), { recursive: true });
  fs.mkdirSync(snapshotsDir(store), { recursive: true });
  const files = {};
  for (const rel of personalFiles(root)) {
    const buf = fs.readFileSync(path.join(root, rel));
    const hash = sha256(buf);
    const obj = path.join(store, "objects", hash);
    if (!fs.existsSync(obj)) fs.writeFileSync(obj, buf);
    files[rel] = { sha256: hash, size: buf.length };
  }
  const stamp = new Date().toISOString().replace(/[-:]/g, "").replace(/\.\d+Z$/, "Z");
  const id = `${stamp}-${label}`;
  let head = "";
  try {
    head = git(["rev-parse", "HEAD"], { cwd: root }).trim();
  } catch {
    head = "";
  }
  const manifest = { id, label, created: new Date().toISOString(), head, files };
  fs.writeFileSync(path.join(snapshotsDir(store), `${id}.json`), JSON.stringify(manifest, null, 2));
  fs.writeFileSync(path.join(store, "LATEST"), id);
  console.log(`snapshot ${id}: ${Object.keys(files).length} files -> ${store}`);
}

function diffAgainst(root, manifest) {
  const current = new Set(personalFiles(root));
  const missing = [];
  const changed = [];
  for (const [rel, meta] of Object.entries(manifest.files)) {
    const abs = path.join(root, rel);
    if (!fs.existsSync(abs)) missing.push(rel);
    else if (sha256(fs.readFileSync(abs)) !== meta.sha256) changed.push(rel);
    current.delete(rel);
  }
  return { missing, changed, added: [...current] };
}

function cmdVerify(root) {
  const manifest = resolveSnapshot(storeDir(), args[1]);
  const { missing, changed, added } = diffAgainst(root, manifest);
  for (const p of missing) console.log(`missing  ${p}`);
  for (const p of changed) console.log(`changed  ${p}`);
  for (const p of added) console.log(`added    ${p}`);
  const ok = missing.length === 0 && changed.length === 0;
  console.log(`verify ${manifest.id}: ${ok ? "ok" : "DIFFERS"} (missing ${missing.length}, changed ${changed.length}, added ${added.length})`);
  process.exit(ok ? 0 : 1);
}

function isTracked(root, rel) {
  try {
    git(["ls-files", "--error-unmatch", "--", rel], { cwd: root });
    return true;
  } catch {
    return false;
  }
}

function cmdRestore(root) {
  const store = storeDir();
  const manifest = resolveSnapshot(store, args[1]);
  const prefixes = args.slice(2).filter((a) => !a.startsWith("--")).map(toPosix);
  let restored = 0;
  let refused = 0;
  for (const [rel, meta] of Object.entries(manifest.files)) {
    if (prefixes.length && !prefixes.some((p) => rel === p || rel.startsWith(`${p.replace(/\/$/, "")}/`))) continue;
    if (rel !== GIT_EXCLUDE && isTracked(root, rel)) {
      console.log(`refused  ${rel} (now tracked by git; move personal content to a non-colliding path)`);
      refused++;
      continue;
    }
    const abs = path.join(root, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.copyFileSync(path.join(store, "objects", meta.sha256), abs);
    restored++;
  }
  console.log(`restore ${manifest.id}: ${restored} restored, ${refused} refused`);
  process.exit(refused ? 1 : 0);
}

function cmdList(root) {
  const store = storeDir();
  console.log(`store: ${store}`);
  const dir = snapshotsDir(store);
  const ids = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort() : [];
  const latest = fs.existsSync(path.join(store, "LATEST")) ? fs.readFileSync(path.join(store, "LATEST"), "utf8").trim() : "";
  for (const f of ids) console.log(`${f.replace(/\.json$/, "") === latest ? "*" : " "} ${f.replace(/\.json$/, "")}`);
  const files = personalFiles(root);
  console.log(`personal files now: ${files.length}`);
  for (const d of [...PERSONAL_FILES, ...personalSkillDirs(root), "docs/ai"]) {
    console.log(`  ${fs.existsSync(path.join(root, d)) ? "present" : "absent "} ${d}`);
  }
}

// ---------- collisions ----------

function refExists(root, ref) {
  try {
    git(["rev-parse", "--verify", "--quiet", `${ref}^{commit}`], { cwd: root });
    return true;
  } catch {
    return false;
  }
}

function cmdCollisions(root) {
  let refs = [];
  for (let i = 1; i < args.length; i++) if (args[i] === "--ref" && args[i + 1]) refs.push(args[++i]);
  if (args.includes("--all-remotes")) {
    refs = git(["for-each-ref", "--format=%(refname:short)", "refs/remotes"], { cwd: root })
      .split("\n")
      .map((s) => s.trim())
      .filter((r) => r && !r.endsWith("/HEAD"));
  }
  if (!refs.length) refs = [...DEFAULT_REFS];
  try {
    const upstream = git(["rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}"], { cwd: root }).trim();
    if (upstream && !refs.includes(upstream) && !args.includes("--all-remotes")) refs.push(upstream);
  } catch {
    // no upstream configured
  }
  const pathspec = ["AGENTS.local.md", "CLAUDE.local.md", ".claude/settings.local.json", ".claude/skills", ".agents/skills", "docs/ai"];
  const hits = [];
  for (const p of git(["ls-files", "--", ...pathspec], { cwd: root }).split("\n").filter(Boolean)) {
    if (isPersonalPath(p)) hits.push(`index: ${p}`);
  }
  const skipped = [];
  for (const ref of refs) {
    if (!refExists(root, ref)) {
      skipped.push(ref);
      continue;
    }
    const listed = git(["ls-tree", "-r", "--name-only", ref, "--", ...pathspec], { cwd: root }).split("\n").filter(Boolean);
    for (const p of listed) if (isPersonalPath(p)) hits.push(`${ref}: ${p}`);
  }
  if (skipped.length && !quiet) console.log(`skipped missing refs: ${skipped.join(", ")}`);
  if (hits.length) {
    console.log(`collisions: ${hits.length}`);
    for (const h of [...new Set(hits)]) console.log(`  ${h}`);
    process.exit(1);
  }
  if (!quiet) console.log(`collisions: none (${refs.length - skipped.length} refs checked)`);
}

// ---------- sync / check-sync ----------

function parseFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return null;
  const data = {};
  for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (kv) data[kv[1]] = kv[2].trim();
  }
  return data;
}

function expectedWrappers(root) {
  const wrappers = new Map();
  const errors = [];
  for (const base of SKILL_SOURCES) {
    const abs = path.join(root, base);
    if (!fs.existsSync(abs)) continue;
    for (const d of fs.readdirSync(abs, { withFileTypes: true })) {
      if (!d.isDirectory()) continue;
      const source = `${base}/${d.name}/SKILL.md`;
      const file = path.join(root, source);
      if (!fs.existsSync(file)) continue;
      const fm = parseFrontmatter(fs.readFileSync(file, "utf8"));
      if (!fm || !fm.name || !fm.description) {
        errors.push(`${source}: missing name/description frontmatter`);
        continue;
      }
      if (fm.name !== d.name) errors.push(`${source}: name "${fm.name}" differs from folder "${d.name}"`);
      if (wrappers.has(fm.name)) {
        errors.push(`duplicate skill name "${fm.name}": ${wrappers.get(fm.name).source} and ${source}`);
        continue;
      }
      const header = COPIED_KEYS.filter((k) => fm[k] !== undefined).map((k) => `${k}: ${fm[k]}`);
      const body = [
        "---",
        ...header,
        "---",
        WRAPPER_MARKER,
        "",
        `Read and follow \`${source}\` from the repository root; relative links inside it resolve from that folder. It is the only owner of this workflow.`,
        "",
      ].join("\n");
      wrappers.set(fm.name, { source, body });
    }
  }
  return { wrappers, errors };
}

function syncPlan(root) {
  const { wrappers, errors } = expectedWrappers(root);
  const writes = [];
  const removals = [];
  const conflicts = [];
  for (const [name, w] of wrappers) {
    const target = path.join(root, WRAPPER_DIR, name, "SKILL.md");
    if (fs.existsSync(target)) {
      const current = fs.readFileSync(target, "utf8");
      if (!current.includes(WRAPPER_MARKER)) {
        conflicts.push(`${WRAPPER_DIR}/${name}/SKILL.md exists and is not generated; not overwritten`);
        continue;
      }
      if (current === w.body) continue;
    }
    writes.push({ name, target, body: w.body });
  }
  const wrapperRoot = path.join(root, WRAPPER_DIR);
  if (fs.existsSync(wrapperRoot)) {
    for (const d of fs.readdirSync(wrapperRoot, { withFileTypes: true })) {
      if (!d.isDirectory() || wrappers.has(d.name)) continue;
      const file = path.join(wrapperRoot, d.name, "SKILL.md");
      if (fs.existsSync(file) && fs.readFileSync(file, "utf8").includes(WRAPPER_MARKER)) removals.push(d.name);
    }
  }
  return { errors, writes, removals, conflicts };
}

function cmdSync(root) {
  const { errors, writes, removals, conflicts } = syncPlan(root);
  for (const w of writes) {
    fs.mkdirSync(path.dirname(w.target), { recursive: true });
    fs.writeFileSync(w.target, w.body);
  }
  for (const name of removals) fs.rmSync(path.join(root, WRAPPER_DIR, name), { recursive: true });
  const problems = [...errors, ...conflicts];
  for (const p of problems) console.error(`ai-env sync: ${p}`);
  if (!quiet || writes.length || removals.length) {
    console.log(`sync: ${writes.length} wrappers written, ${removals.length} stale removed`);
  }
  process.exit(problems.length ? 1 : 0);
}

function cmdCheckSync(root) {
  const { errors, writes, removals, conflicts } = syncPlan(root);
  const problems = [...errors, ...conflicts, ...writes.map((w) => `out of date: ${WRAPPER_DIR}/${w.name}/SKILL.md`), ...removals.map((n) => `stale: ${WRAPPER_DIR}/${n}`)];
  for (const p of problems) console.log(`check-sync: ${p}`);
  console.log(`check-sync: ${problems.length ? "FAIL" : "ok"}`);
  process.exit(problems.length ? 1 : 0);
}

const root = repoRoot();
const commands = {
  list: cmdList,
  snapshot: cmdSnapshot,
  verify: cmdVerify,
  restore: cmdRestore,
  collisions: cmdCollisions,
  sync: cmdSync,
  "check-sync": cmdCheckSync,
};
if (!commands[command]) {
  fail("usage: ai-env.mjs list|snapshot <label>|verify [id]|restore <id> [paths]|collisions [--ref r] [--all-remotes] [--quiet]|sync [--quiet]|check-sync", 2);
}
commands[command](root);
