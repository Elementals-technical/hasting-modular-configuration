/**
 * Countertop behaviour per cabinet collection: the ONE place to connect a collection to cabinet
 * covers and to a basin top policy. Connect a collection (e.g. Urban Duplex) = add one entry.
 * Its products also need a working `countertopSupport` in product-config-loader (anchorName + a
 * fallback mesh that exists in the model): covers and policies measure cabinets through it.
 * Full description: docs/features/countertop-collections/README.md
 *
 *   compatibilityKey       supports with different keys never share one cover
 *   sourceTypes            cabinet product types that may carry a cover
 *   lineTypes              optional: other cabinet types of the same line (e.g. UF open shelves).
 *                          They count as the collection's cabinets for basinTopPolicy and
 *                          enabledByDefault, but never get a cover (the cover adapter skips them).
 *   freeLayoutSourceTypes  extra cover sources only while the modular runtime owns the composition
 *   enabledByDefault       true: covers are on while every cabinet of the composition belongs to this
 *                          collection and no other settings are saved (no modular runtime sets them).
 *                          false: covers are configured by the modular runtime (ULH).
 *   basinTopPolicy         id from basin-top-policies.mjs, or null: on which cabinets of a line with
 *                          mixed heights the basin top lies (the rest get covers). null = all cabinets.
 *
 * The table is module-private: callers get answers from the functions below, never the objects,
 * so nothing needs freezing.
 */
const COUNTERTOP_COLLECTIONS = [
    {
        id: 'ULH',
        compatibilityKey: 'ulh-flat',
        sourceTypes: ['ULH-sink-cabinet', 'ULH-side-cabinet'],
        freeLayoutSourceTypes: ['ULH-Open-Shelf'],
        enabledByDefault: false,
        basinTopPolicy: null
    },
    {
        // Urban Duplex: a modular collection like ULH, so the modular runtime turns covers on.
        id: 'UD',
        compatibilityKey: 'ud-flat',
        sourceTypes: ['UD-sink-cabinet', 'UD-side-cabinet'],
        // OSS is a line type, never a cover source (Andriy 16.10): under one basin top it is exactly as high as the
        // cabinet (the top lies on both); beside a separate cover it reaches the cover top itself and continues the
        // slab, so no cover lies on it. The cover planner skips line types, so it never measures the OSS (whose
        // mirror is a negative scale). OS supports a cover in the modular runtime like ULH-Open-Shelf. Without them
        // in the collection the cover plan refused the whole composition (unsupported-cover-profile-source).
        lineTypes: ['UD-open-shelves-side'],
        freeLayoutSourceTypes: ['UD-open-shelves'],
        enabledByDefault: false,
        basinTopPolicy: null
    },
    {
        id: 'UF',
        compatibilityKey: 'uf-flat',
        sourceTypes: ['UF-sink-cabinet', 'UF-side-cabinet'],
        // Open shelves stand in the UF line under the basin top; without them in the line the
        // whole line lost its policy (top over the short cabinet) and its default covers.
        lineTypes: ['UF-open-shelves', 'UF-open-shelves-side'],
        freeLayoutSourceTypes: [],
        enabledByDefault: true,
        basinTopPolicy: 'highest-plane'
    }
];

// productType -> its collection (every cover source type, free-layout ones included).
const collectionByType = new Map();
for (const collection of COUNTERTOP_COLLECTIONS) {
    for (const type of [...collection.sourceTypes, ...collection.freeLayoutSourceTypes]) {
        collectionByType.set(type, collection);
    }
}

// productType -> its collection, for every cabinet type of a line (cover sources + lineTypes).
const collectionByLineType = new Map();
for (const collection of COUNTERTOP_COLLECTIONS) {
    for (const type of [...collection.sourceTypes, ...(collection.lineTypes ?? [])]) {
        collectionByLineType.set(type, collection);
    }
}

// Cover products generated by the cover service; they are not cabinets of the line.
const GENERATED_COVER = 'cabinet-cover-v1';

const read = (snapshot, key) => typeof snapshot?.get === 'function' ? snapshot.get(key) : snapshot?.[key];

/** compatibilityKey of a cover source type (free-layout sources included), else null. */
export function coverCompatibilityKey(productType) {
    return collectionByType.get(productType)?.compatibilityKey ?? null;
}

/** May this cabinet type carry a cover? Free-layout-only sources (ULH open shelf) need `freeLayout`. */
export function isCoverSource(productType, { freeLayout = false } = {}) {
    const collection = collectionByType.get(productType);
    if (!collection) return false;
    if (collection.sourceTypes.includes(productType)) return true;
    return freeLayout && collection.freeLayoutSourceTypes.includes(productType);
}

/**
 * Is this cabinet type part of a collection's line without being a cover source?
 * The cover adapter skips such cabinets instead of rejecting the whole plan.
 * 'UF-open-shelves' -> true; 'UF-side-cabinet' -> false (a cover source); unknown type -> false.
 */
export function isLineOnlyType(productType) {
    const collection = collectionByLineType.get(productType);
    return collection?.lineTypes?.includes(productType) ?? false;
}

/**
 * The collection that owns ALL the given cabinet types (cover sources or lineTypes), else null.
 * Empty list, an unknown type or a mix of collections -> null (no collection-specific behaviour).
 * ['UF-sink-cabinet', 'UF-open-shelves', 'UF-side-cabinet'] -> UF.
 */
function ownerOf(productTypes) {
    const owner = collectionByLineType.get(productTypes[0]);
    // Empty list or a type no collection knows: nothing owns the line.
    if (!owner) return null;
    const allOfOwner = productTypes.every(type => collectionByLineType.get(type) === owner);
    return allOfOwner ? owner : null;
}

/** basinTopPolicy id of the collection owning ALL these cabinet types, else null. UF line -> 'highest-plane'. */
export function basinTopPolicyOf(productTypes) {
    return ownerOf(productTypes)?.basinTopPolicy ?? null;
}

/**
 * Cover settings for a composition that has none saved, else null.
 * Only when one enabledByDefault collection owns all its cabinets (UF line -> covers on).
 * Returns a fresh object every call (callers may store or change it).
 */
export function defaultCoverSettingsFor(composition) {
    // 1. Cabinet types of the line (generated covers are not cabinets of the line).
    const products = composition?.getAllProducts?.() ?? {};
    const snapshots = products instanceof Map ? [...products.values()] : Object.values(products);
    const cabinets = snapshots.filter(snapshot =>
        read(snapshot, 'category') === 'cabinets' && read(snapshot, 'generatedBy') !== GENERATED_COVER);
    const productTypes = cabinets.map(snapshot => read(snapshot, 'productType'));

    // 2. Not a single enabledByDefault collection (ULH, other collections, mixed line) -> no default.
    if (!ownerOf(productTypes)?.enabledByDefault) return null;

    return {
        enabled: true,
        profileId: 'ulh-v1',          // the only profile id the cover adapter accepts
        eligibilityMode: 'all',       // every cabinet not under the basin top gets a cover
        thicknessM: 0.0128,           // Top_Solid slab thickness (template measurement)
        tolerances: {
            contactM: 0.001,          // top touches a cabinet: |dY| <= 1 mm
            adjacencyM: 0.001,        // cabinets are neighbours: X gap <= 1 mm
            numericalM: 1e-6          // float noise
        }
    };
}
